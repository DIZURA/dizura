import { z } from "zod";
import { BLUEPRINT_GOALS, BLUEPRINT_SECTIONS } from "@/lib/ai/claude";
import { requireUser } from "@/lib/auth/session";
import { blueprints } from "@/lib/blueprints/store";
import { STRATEGY } from "@/lib/credits/pricing";
import { credits } from "@/lib/credits/store";
import { requireEnv } from "@/lib/env";
import { ok, parseJson, route } from "@/lib/http";
import { rateLimit } from "@/lib/security/rate-limit";

export const runtime = "nodejs";

const text = (max: number) => z.string().trim().max(max).default("");
const body = z.object({
  goal: z.enum(BLUEPRINT_GOALS),
  title: z.string().trim().min(1).max(120).optional(),
  locale: z.enum(["ar", "en"]).default("ar"),
  inputs: z.object({
    product: z.string().trim().min(2).max(300),
    audience: text(300),
    market: text(120),
    budget: text(80),
    tone: text(80),
    notes: text(1000),
    /** Recent strategist chat (plain text) to ground the blueprint. */
    context: text(4000),
  }),
});

/** GET → the caller's blueprints (newest first). */
export const GET = route(async (req: Request) => {
  const user = await requireUser(req);
  rateLimit(`bp:list:${user.id}`, 60, 60_000);
  const list = await blueprints().list(user.id);
  return ok(
    list.map((b) => ({
      id: b.id, title: b.title, goal: b.goal, locale: b.locale, tags: b.tags, createdAt: b.createdAt,
      done: BLUEPRINT_SECTIONS.filter((s) => b.sections[s] !== undefined).length,
    })),
  );
});

/**
 * POST → creates a blueprint and charges STRATEGY.blueprintCredits once. The four sections are then
 * generated by POST /api/blueprints/[id]/sections/[section] (one per request, each < 60 s).
 */
export const POST = route(async (req: Request) => {
  const user = await requireUser(req);
  rateLimit(`bp:create:${user.id}`, 5, 10 * 60_000);
  const input = await parseJson(req, body, 32 * 1024);
  requireEnv("ANTHROPIC_API_KEY"); // fail before charging

  const title = input.title ?? input.inputs.product.slice(0, 120);
  const bp = await blueprints().create({
    userId: user.id, title, goal: input.goal, locale: input.locale, inputs: { ...input.inputs, goal: input.goal }, creditsCharged: STRATEGY.blueprintCredits,
  });
  try {
    await credits().apply({ userId: user.id, delta: -STRATEGY.blueprintCredits, reason: "generation", referenceId: `bp:${bp.id}` });
  } catch (err) {
    await blueprints().remove(bp.id, user.id); // e.g. insufficient credits: leave nothing behind
    throw err;
  }
  return ok({ ...bp, sections: {} }, { status: 201 });
});
